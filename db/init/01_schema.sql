-- 01_schema.sql: Initial schema setup for IoT platform

-- Extensions
CREATE EXTENSION IF NOT EXISTS timescaledb;
CREATE EXTENSION IF NOT EXISTS citext;

-- Schemas
CREATE SCHEMA IF NOT EXISTS app;
CREATE SCHEMA IF NOT EXISTS telemetry;
CREATE SCHEMA IF NOT EXISTS mqtt;

-- ============================================================================
-- APP SCHEMA (Metadata & Control Plane)
-- ============================================================================

-- Human accounts (Flutter app login)
CREATE TABLE IF NOT EXISTS app.users (
    id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username      CITEXT UNIQUE NOT NULL
                  CHECK (username ~ '^[a-zA-Z0-9_.-]{3,32}$'),
    password_hash TEXT NOT NULL,               -- Argon2id (API verification)
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    is_admin      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Refresh tokens for JWT session renewal
CREATE TABLE IF NOT EXISTS app.refresh_tokens (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
    token_hash  TEXT UNIQUE NOT NULL,          -- SHA-256 of opaque token
    expires_at  TIMESTAMPTZ NOT NULL,
    revoked_at  TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user ON app.refresh_tokens (user_id);

-- Channels
CREATE TABLE IF NOT EXISTS app.channels (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    description TEXT,
    is_public   BOOLEAN NOT NULL DEFAULT FALSE,
    max_fields  INT NOT NULL DEFAULT 500,      -- Guardrail against field bloat
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_channels_owner ON app.channels (owner_id);

-- MQTT identities for hardware (ESP32, sensors)
CREATE TABLE IF NOT EXISTS app.devices (
    id                 BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    channel_id         BIGINT NOT NULL REFERENCES app.channels(id) ON DELETE CASCADE,
    name               TEXT NOT NULL,
    mqtt_username      TEXT UNIQUE NOT NULL,   -- e.g. 'd_xxxx' generated by API
    mqtt_password_hash TEXT NOT NULL,          -- Bcrypt hash for mosquitto-go-auth
    scope              TEXT NOT NULL DEFAULT 'publish' CHECK (scope IN ('publish', 'subscribe', 'pubsub')),
    is_active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_devices_channel ON app.devices (channel_id);

-- Short-lived MQTT credentials for Flutter app sessions (issued after login)
CREATE TABLE IF NOT EXISTS app.mqtt_sessions (
    username      TEXT PRIMARY KEY,            -- e.g. 's_xxxx'
    user_id       BIGINT NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
    password_hash TEXT NOT NULL,               -- Bcrypt hash
    expires_at    TIMESTAMPTZ NOT NULL,
    revoked_at    TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_mqtt_sessions_user ON app.mqtt_sessions (user_id);

-- Internal service accounts (bridge, API publisher) -> superusers in go-auth
CREATE TABLE IF NOT EXISTS app.service_accounts (
    username      TEXT PRIMARY KEY,            -- 'svc_bridge', 'svc_api'
    password_hash TEXT NOT NULL                -- Bcrypt hash
);

-- HTTP API keys (ThingSpeak-style REST ingest/export)
CREATE TABLE IF NOT EXISTS app.api_keys (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    channel_id   BIGINT NOT NULL REFERENCES app.channels(id) ON DELETE CASCADE,
    prefix       TEXT NOT NULL,                -- First 8 chars displayed in UI
    key_hash     TEXT UNIQUE NOT NULL,         -- SHA-256 hash of complete key
    scope        TEXT NOT NULL CHECK (scope IN ('read', 'write')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ,
    revoked_at   TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_api_keys_lookup ON app.api_keys (key_hash);

-- Field registry (auto-discovered by bridge, editable in Flutter app)
CREATE TABLE IF NOT EXISTS app.channel_fields (
    id            INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    channel_id    BIGINT NOT NULL REFERENCES app.channels(id) ON DELETE CASCADE,
    key           TEXT NOT NULL CHECK (key ~ '^[A-Za-z0-9_.-]{1,64}$'),
    label         TEXT,
    unit          TEXT,
    value_type    TEXT NOT NULL DEFAULT 'number'
                  CHECK (value_type IN ('number', 'string', 'boolean')),
    widget_type   TEXT NOT NULL DEFAULT 'line'
                  CHECK (widget_type IN ('line', 'gauge', 'kpi', 'status')),
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (channel_id, key)
);
CREATE INDEX IF NOT EXISTS idx_channel_fields_lookup ON app.channel_fields (channel_id, key);

-- User-customizable dashboard widgets in Flutter app
CREATE TABLE IF NOT EXISTS app.dashboard_widgets (
    id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
    channel_id BIGINT NOT NULL REFERENCES app.channels(id) ON DELETE CASCADE,
    position   INT NOT NULL DEFAULT 0,
    config     JSONB NOT NULL                  -- e.g. {type: 'line', field_ids: [1, 2], range: '24h'}
);
CREATE INDEX IF NOT EXISTS idx_widgets_user ON app.dashboard_widgets (user_id);


-- ============================================================================
-- TELEMETRY SCHEMA (High-throughput TimescaleDB Hypertables)
-- ============================================================================

-- 1) Narrow numeric values (charts, continuous aggregates)
CREATE TABLE IF NOT EXISTS telemetry.points (
    time       TIMESTAMPTZ      NOT NULL,
    channel_id BIGINT           NOT NULL,
    field_id   INT              NOT NULL,
    value      DOUBLE PRECISION NOT NULL
);

-- Convert to Hypertable (1-day chunk intervals)
SELECT create_hypertable('telemetry.points', 'time',
                         chunk_time_interval => INTERVAL '1 day',
                         if_not_exists => TRUE);

CREATE INDEX IF NOT EXISTS idx_points_query ON telemetry.points (channel_id, field_id, time DESC);

-- Enable columnar compression
ALTER TABLE telemetry.points SET (
    timescaledb.compress,
    timescaledb.compress_segmentby = 'channel_id, field_id',
    timescaledb.compress_orderby   = 'time DESC'
);

-- Compress chunks older than 3 days, drop raw points older than 90 days
SELECT add_compression_policy('telemetry.points', INTERVAL '3 days', if_not_exists => TRUE);
SELECT add_retention_policy('telemetry.points', INTERVAL '90 days', if_not_exists => TRUE);


-- 2) Raw JSON payloads (auditing, non-numeric fields, full message inspection)
CREATE TABLE IF NOT EXISTS telemetry.messages (
    time       TIMESTAMPTZ NOT NULL,
    channel_id BIGINT      NOT NULL,
    payload    JSONB       NOT NULL
);

SELECT create_hypertable('telemetry.messages', 'time',
                         chunk_time_interval => INTERVAL '1 day',
                         if_not_exists => TRUE);

CREATE INDEX IF NOT EXISTS idx_messages_query ON telemetry.messages (channel_id, time DESC);

ALTER TABLE telemetry.messages SET (
    timescaledb.compress,
    timescaledb.compress_segmentby = 'channel_id',
    timescaledb.compress_orderby   = 'time DESC'
);

SELECT add_compression_policy('telemetry.messages', INTERVAL '3 days', if_not_exists => TRUE);
SELECT add_retention_policy('telemetry.messages', INTERVAL '30 days', if_not_exists => TRUE);


-- ============================================================================
-- CONTINUOUS AGGREGATES (Downsampling for Fast Visualizations)
-- ============================================================================

-- 1-minute Rollups
CREATE MATERIALIZED VIEW IF NOT EXISTS telemetry.points_1m
WITH (timescaledb.continuous) AS
SELECT time_bucket(INTERVAL '1 minute', time) AS bucket,
       channel_id,
       field_id,
       avg(value) AS avg_v,
       min(value) AS min_v,
       max(value) AS max_v,
       count(*)   AS n
FROM telemetry.points
GROUP BY time_bucket(INTERVAL '1 minute', time), channel_id, field_id
WITH NO DATA;

SELECT add_continuous_aggregate_policy('telemetry.points_1m',
    start_offset      => INTERVAL '2 hours',
    end_offset        => INTERVAL '1 minute',
    schedule_interval => INTERVAL '1 minute',
    if_not_exists     => TRUE);

SELECT add_retention_policy('telemetry.points_1m', INTERVAL '1 year', if_not_exists => TRUE);


-- 1-hour Rollups
CREATE MATERIALIZED VIEW IF NOT EXISTS telemetry.points_1h
WITH (timescaledb.continuous) AS
SELECT time_bucket(INTERVAL '1 hour', time) AS bucket,
       channel_id,
       field_id,
       avg(value) AS avg_v,
       min(value) AS min_v,
       max(value) AS max_v,
       count(*)   AS n
FROM telemetry.points
GROUP BY time_bucket(INTERVAL '1 hour', time), channel_id, field_id
WITH NO DATA;

SELECT add_continuous_aggregate_policy('telemetry.points_1h',
    start_offset      => INTERVAL '1 day',
    end_offset        => INTERVAL '1 hour',
    schedule_interval => INTERVAL '30 minutes',
    if_not_exists     => TRUE);
-- 1-hour rollups are retained long-term
